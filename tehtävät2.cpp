// koordinatit
struct Sijainti {
    int y;
    int x;
    
    bool operator<(const Sijainti& other) const {
        if (y != other.y) return y < other.y;
        return x < other.x;
    }
    
    bool operator==(const Sijainti& other) const {
        return y == other.y && x == other.x;
    }
};

// etsi aloituspisteet labyrintissa
Sijainti etsiAloitus() {
    for (int y = 0; y < KORKEUS; y++) {
        for (int x = 0; x < LEVEYS; x++) {
            if (labyrintti[y][x] == 3) {
                return {y, x};
            }
        }
    }
    return {0, 0};
}

// etsi lopetuspisteet labyrintissa
Sijainti etsiLopetus() {
    for (int y = 0; y < KORKEUS; y++) {
        for (int x = 0; x < LEVEYS; x++) {
            if (labyrintti[y][x] == 4) {
                return {y, x};
            }
        }
    }
    return {0, 0};
}

// tarkista onko liikkuminen mahdollista
bool voiLiikkua(Sijainti s) {
    if (s.y < 0 || s.y >= KORKEUS || s.x < 0 || s.x >= LEVEYS) {
        return false;
    }
    return labyrintti[s.y][s.x] != 1;
}

// Rotta liikkuu eteenpäin niin kauan kuin se voi, ja kun se törmää umpikujaan, se peruuttaa askelen ja yrittää toista reittiä.
int ajaRotta(int ratId, bool useThreads) {
    set<Sijainti> kaydyt;
    vector<Sijainti> polku;
    int liikkeet = 0;
    
    Sijainti nykyinen = etsiAloitus();
    Sijainti maali = etsiLopetus();
    
    polku.push_back(nykyinen);
    kaydyt.insert(nykyinen);
    
    pthread_mutex_lock(&coutMutex);
    cout << "Rotta " << ratId << " aloittaa (" << nykyinen.y << "," << nykyinen.x << ")" << endl;
    pthread_mutex_unlock(&coutMutex);
    
    // pääsilmukka joka pyörii kunnes liikkumisraja saavutetaan
    while (liikkeet < STEP_LIMIT) {
        if (nykyinen.y == maali.y && nykyinen.x == maali.x) {
            pthread_mutex_lock(&coutMutex);
            cout << "*** Rotta " << ratId << " pääsi ulos! Liikkeet: " << liikkeet << " ***" << endl;
            pthread_mutex_unlock(&coutMutex);
            return liikkeet;
        }
        
        // kokeile liikkua kaikkiin suuntiin
        vector<Sijainti> naapurit = {
            {nykyinen.y-1, nykyinen.x},
            {nykyinen.y+1, nykyinen.x},
            {nykyinen.y, nykyinen.x-1},
            {nykyinen.y, nykyinen.x+1}
        };
        
        bool liikuttu = false;
        
        // käydään läpi kaikki naapuriruudut
        for (Sijainti naapuri : naapurit) {
            // tarkistetaan voiko liikkua ja onko kohde käymätön
            if (voiLiikkua(naapuri) && kaydyt.find(naapuri) == kaydyt.end()) {
                nykyinen = naapuri;
                polku.push_back(nykyinen);
                kaydyt.insert(nykyinen);
                liikuttu = true;
                break;
            }
        }
        
        // tarkistetaan ettei liikuttu mihinkään suuntaan
        if (!liikuttu) {
            if (polku.size() > 1) {
                polku.pop_back();
                nykyinen = polku.back();
            } else {
                break;
            }
        }
        
        // kasvatetaan rotan liikkeiden määrää
        liikkeet++;
        
        // väliaikainen tulostus debuggaamiseksi
        if (liikkeet % 200 == 0) {
            pthread_mutex_lock(&coutMutex);
            cout << "Rotta " << ratId << " liikkeellä " << liikkeet 
                 << " sijainnissa (" << nykyinen.y << "," << nykyinen.x 
                 << ") arvo: " << labyrintti[nykyinen.y][nykyinen.x] << endl;
            pthread_mutex_unlock(&coutMutex);
        }
        
        // tarkistetaan käytetäänkö säikeitä
        if (useThreads) {
            usleep(1000);
        }
    }
    
    pthread_mutex_lock(&coutMutex);
    cout << "Rotta " << ratId << " ei päässyt ulos. Liikkeet: " << liikkeet 
         << ", viimeinen: (" << nykyinen.y << "," << nykyinen.x 
         << ") arvo: " << labyrintti[nykyinen.y][nykyinen.x] << endl;
    pthread_mutex_unlock(&coutMutex);
    
    return liikkeet;
}

// säikefunktio
void* aloitaRottaThread(void* arg) {
    int ratId = *((int*)arg);
    int tulos = ajaRotta(ratId, true);
    
    int* palautus = new int;
    *palautus = tulos;
    return palautus;
}

// prosessifunktio
void aloitaRottaProsessi(int ratId) {
    ajaRotta(ratId, false);
    exit(0);
}

